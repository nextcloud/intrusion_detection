	public function testEveryRouteKeepsItsUrlAndAttributes(): void {
		$this->assertSame(self::ROUTES, RouteTable::routes());
	}

	public function testTheSpecsKeepTheirOperations(): void {
		foreach (self::SPECS as $file => $operations) {
			$spec = json_decode((string)file_get_contents(__DIR__ . '/../../../' . $file), true, flags: JSON_THROW_ON_ERROR);
			$found = [];
			foreach ($spec['paths'] as $path => $methods) {
				foreach (array_keys($methods) as $method) {
					if (in_array($method, ['get', 'post', 'put', 'delete', 'patch'], true)) {
						$found[] = strtoupper($method) . ' ' . str_replace('/ocs/v2.php/apps/intrusion_detection', '', $path);
					}
				}
			}
			sort($found);
			$this->assertSame($operations, $found, $file);
		}
	}
