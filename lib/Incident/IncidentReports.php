namespace OCA\IntrusionDetection\Incident;

use OCA\IntrusionDetection\Audit\AuditLogger;
use OCP\IL10N;

/**
 * Generates incident reports for the admin page and occ, and writes every
 * one of them to the audit log: who asked, about whom, for which period,
 * and in which form. Nothing of the report itself is stored.
 */
class IncidentReports {
	public function __construct(
		private readonly IncidentReportBuilder $builder,
		private readonly ReportRenderer $renderer,
		private readonly AuditLogger $audit,
	) {
	}

	public function report(IncidentQuery $query, string $actor, IL10N $l): IncidentReport {
		$this->audit($query, ReportFormat::Screen, $actor);
		return $this->builder->build($query, $actor, $l);
	}

	/**
	 * @return array{body: string, filename: string, contentType: string}
	 */
	public function document(IncidentQuery $query, ReportFormat $format, string $actor, IL10N $l): array {
		$this->audit($query, $format, $actor);
		$report = $this->builder->build($query, $actor, $l);
		return [
			'body' => $format === ReportFormat::Html ? $this->renderer->html($report, $l) : $this->renderer->json($report),
			'filename' => $this->renderer->filename($report, $format),
			'contentType' => $format->contentType(),
		];
	}

	private function audit(IncidentQuery $query, ReportFormat $format, string $actor): void {
		$this->audit->log('incident report about the %s %s from %s to %s generated by %s as %s', [
			'subjectType' => $query->subjectType,
			'subject' => $query->subject(),
			'since' => gmdate('Y-m-d\TH:i:s\Z', $query->since),
			'until' => gmdate('Y-m-d\TH:i:s\Z', $query->until),
			'actor' => $actor,
			'format' => $format->value,
		]);
	}
}
